import { readFile, writeFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { parseHTML } from 'linkedom';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = (name) => readFile(path.join(root, name), 'utf8');
const config = JSON.parse(await read('site.config.json'));
const zh = JSON.parse(await read('lang/zh.json'));
const base = new URL(config.url);
if (base.protocol !== 'https:') throw new Error('site.config.json.url must use HTTPS');
if (!base.pathname.endsWith('/')) base.pathname += '/';
const absolute = (name) => new URL(name, base).href;
const blogUrl = config.blogUrl ? new URL(config.blogUrl).href : '';
if (blogUrl && !['https:', 'http:'].includes(new URL(blogUrl).protocol)) throw new Error('blogUrl must be an HTTP(S) URL');
if (blogUrl && new URL(blogUrl).origin === base.origin && new URL(blogUrl).pathname.startsWith(`${base.pathname}pages/posts/`)) throw new Error('blogUrl must not redirect back to the paused blog pages');
const get = (key) => key.split('.').reduce((value, part) => value?.[part], zh) ?? key;

async function htmlFiles(dir = root) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (['node_modules', '.git', 'test-results', 'playwright-report', 'templates', '_site'].includes(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...await htmlFiles(full));
    else if (entry.name.endsWith('.html')) files.push(full);
  }
  return files.sort();
}

const fallbackSource = `// Generated by npm run generate. Edit lang/zh.json instead.\nwindow.SiteDefaultLocale = ${JSON.stringify(zh)};\n`;
await writeFile(path.join(root, 'assets/js/fallback-zh.js'), fallbackSource);
await writeFile(path.join(root, 'assets/js/site-config.js'), `// Generated by npm run generate. Edit site.config.json instead.\nwindow.SiteConfig = ${JSON.stringify({ blogUrl })};\n`);
const scripts = {};
const blogTemplate = await read('templates/blog-placeholder.html');
for (const name of ['shared.js', 'site-data.js', 'render.js']) {
  scripts[name] = await read(`assets/js/${name}`);
}

const files = await htmlFiles();
const urls = [];
for (const file of files) {
  const relative = path.relative(root, file).replaceAll('\\', '/');
  const prefix = relative.includes('/') ? '../../' : '';
  const { document } = parseHTML(await readFile(file, 'utf8'));
  const isBlogPlaceholder = relative === 'pages/posts/index.html';
  if (isBlogPlaceholder) {
    const { document: fragment } = parseHTML(`<!DOCTYPE html><html><body>${blogTemplate}</body></html>`);
    document.querySelector('main').replaceWith(fragment.querySelector('main'));
    document.body.className = 'blog-placeholder-page';
    document.body.setAttribute('data-blog-placeholder', '');
    document.documentElement.setAttribute('data-title-i18n', 'meta.blogTitle');
  }
  for (const link of document.querySelectorAll('[data-i18n="nav.blog"], [data-i18n="home.secondaryCta"], [data-blog-link]')) {
    link.setAttribute('data-blog-link', '');
    link.setAttribute('href', blogUrl || `${prefix}pages/posts/index.html`);
  }
  if (!document.querySelector('script[src$="site-config.js"]')) {
    const script = document.createElement('script');
    script.setAttribute('src', `${prefix}assets/js/site-config.js`);
    script.setAttribute('defer', '');
    document.querySelector('script[src$="shared.js"]').after('\n  ', script);
  }
  const sandbox = {
    document,
    localStorage: { getItem: () => null, setItem() {} },
    i18n: { get, currentLang: () => 'zh' },
  };
  sandbox.window = sandbox;
  Object.defineProperty(document, 'currentScript', {
    configurable: true,
    value: { getAttribute: () => `${prefix}assets/js/shared.js` },
  });
  const context = vm.createContext(sandbox);
  for (const [name, source] of Object.entries(scripts)) {
    vm.runInContext(source, context, { filename: name });
  }
  for (const el of document.querySelectorAll('[data-i18n]')) {
    const value = get(el.getAttribute('data-i18n'));
    if (el.tagName === 'IMG') el.setAttribute('alt', value);
    else el.innerHTML = value;
  }
  sandbox.SiteHome.render();

  const titleKey = document.documentElement.getAttribute('data-title-i18n');
  if (titleKey) document.title = get(titleKey);
  const existingDescription = document.querySelector('meta[name="description"]')?.content;
  const description = isBlogPlaceholder ? zh.blogStatus.description : existingDescription;
  const url = isBlogPlaceholder ? blogUrl || absolute('pages/posts/index.html') : absolute(relative === 'index.html' ? '' : relative);
  if (!isBlogPlaceholder) urls.push(url);
  function meta(attribute, key, content) {
    let el = document.head.querySelector(`meta[${attribute}="${key}"]`);
    if (!el) { el = document.createElement('meta'); el.setAttribute(attribute, key); document.head.appendChild(el); }
    el.setAttribute('content', content);
  }
  meta('name', 'description', description);
  if (isBlogPlaceholder) {
    meta('name', 'robots', 'noindex, follow');
    document.querySelector('meta[http-equiv="refresh"]')?.remove();
    if (blogUrl) {
      const redirect = document.createElement('meta');
      redirect.setAttribute('http-equiv', 'refresh');
      redirect.content = `0; url=${blogUrl}`;
      document.head.appendChild(redirect);
    }
  }
  meta('name', 'author', config.author);
  meta('property', 'og:type', 'website');
  meta('property', 'og:site_name', config.name);
  meta('property', 'og:title', document.title);
  meta('property', 'og:description', description);
  meta('property', 'og:url', url);
  meta('property', 'og:image', absolute(config.image));
  meta('property', 'og:image:alt', zh.intro.avatarAlt);
  meta('property', 'og:locale', 'zh_CN');
  meta('name', 'twitter:card', 'summary');
  meta('name', 'twitter:title', document.title);
  meta('name', 'twitter:description', description);
  meta('name', 'twitter:image', absolute(config.image));
  let canonical = document.head.querySelector('link[rel="canonical"]');
  if (!canonical) { canonical = document.createElement('link'); canonical.rel = 'canonical'; document.head.appendChild(canonical); }
  canonical.href = url;
  let schema = document.getElementById('page-schema');
  if (!schema) { schema = document.createElement('script'); schema.id = 'page-schema'; schema.type = 'application/ld+json'; document.head.appendChild(schema); }
  const author = { '@type': 'Person', name: config.author, url: base.href };
  const data = { '@context': 'https://schema.org', '@type': 'WebPage',
    name: document.title, description, url, inLanguage: 'zh-CN', author,
    image: absolute(config.image) };
  schema.textContent = JSON.stringify(data).replaceAll('<', '\\u003c');
  // Keep head additions legible and generation byte-for-byte reproducible.
  for (const el of document.head.querySelectorAll('meta, link[rel="canonical"], #page-schema')) {
    if (el.previousSibling?.nodeType !== 3) el.before('\n  ');
  }
  await writeFile(file, ('<!DOCTYPE html>\n' + document.documentElement.outerHTML + '\n').replace(/[\t ]+$/gm, ''));
}

const xmlEscape = (value) => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('"', '&quot;');
await writeFile(path.join(root, 'sitemap.xml'), '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + urls.map((url) => `  <url><loc>${xmlEscape(url)}</loc></url>`).join('\n') + '\n</urlset>\n');
await writeFile(path.join(root, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${absolute('sitemap.xml')}\n`);
await writeFile(path.join(root, '.nojekyll'), '');
console.log(`Generated static content and SEO for ${files.length} pages.`);
